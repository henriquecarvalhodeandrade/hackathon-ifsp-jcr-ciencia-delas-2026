  on public.forum_posts for insert
  to authenticated
  with check (
    (
      (not is_anonymous and author_id = (select auth.uid()))
      or (
        is_anonymous and author_id is null
        and private.is_anonymous_post_author(id)
      )
    )
    and exists (
      select 1 from public.forum_threads t
      where t.id = thread_id and (not t.is_locked or (select private.is_moderator()))
    )
  );

create policy "Autora ou moderação editam a resposta"
  on public.forum_posts for update
  to authenticated
  using (
    author_id = (select auth.uid())
    or (is_anonymous and private.is_anonymous_post_author(id))
    or (select private.is_moderator())
  )
  with check (
    author_id = (select auth.uid())
    or (is_anonymous and private.is_anonymous_post_author(id))
    or (select private.is_moderator())
  );

create policy "Autora ou moderação apagam a resposta"
  on public.forum_posts for delete
  to authenticated
  using (
    author_id = (select auth.uid())
    or (is_anonymous and private.is_anonymous_post_author(id))
    or (select private.is_moderator())
  );

