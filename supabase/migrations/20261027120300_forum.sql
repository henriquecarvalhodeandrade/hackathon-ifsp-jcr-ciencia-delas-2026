create table public.forum_threads (
  id uuid primary key default gen_random_uuid(),
  category_id smallint not null references public.forum_categories (id) on delete restrict,
  author_id uuid default auth.uid() references public.profiles (id) on delete cascade,
  is_anonymous boolean not null default false,
  title text not null check (char_length(title) between 5 and 160),
  body text not null check (char_length(body) between 10 and 20000),
  tags text[] not null default '{}'
    check (private.text_array_ok(tags, 5, 40) and tags = private.normalize_tags(tags)),
  is_pinned boolean not null default false,
  is_locked boolean not null default false,
  solution_post_id uuid,
  reply_count integer not null default 0 check (reply_count >= 0),
  last_activity_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  edited_at timestamptz,
  constraint forum_threads_author_consistency check (
    (is_anonymous and author_id is null) or (not is_anonymous and author_id is not null)
  )
);
comment on column public.forum_threads.author_id is
  'Autora do tópico. NULL quando is_anonymous (a autoria real fica em forum_anonymous_authorship).';

create index forum_threads_category_activity_idx on public.forum_threads
  (category_id, is_pinned desc, last_activity_at desc);
create index forum_threads_last_activity_idx on public.forum_threads (last_activity_at desc);
create index forum_threads_author_id_idx on public.forum_threads (author_id);
create index forum_threads_solution_post_id_idx on public.forum_threads (solution_post_id);
create index forum_threads_tags_idx on public.forum_threads using gin (tags);
create index forum_threads_title_trgm_idx on public.forum_threads
  using gin (title extensions.gin_trgm_ops);

