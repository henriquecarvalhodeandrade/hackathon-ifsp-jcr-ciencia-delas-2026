-- -----------------------------------------------------------------------------
-- forum_reactions (+ views de contagem)
-- -----------------------------------------------------------------------------
create table public.forum_reactions (
  id bigint generated always as identity primary key,
  user_id uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  thread_id uuid references public.forum_threads (id) on delete cascade,
  post_id uuid references public.forum_posts (id) on delete cascade,
  kind public.reaction_kind not null,
  created_at timestamptz not null default now(),
  constraint forum_reactions_one_target check (num_nonnulls(thread_id, post_id) = 1),
  constraint forum_reactions_unique unique nulls not distinct (user_id, thread_id, post_id, kind)
);
create index forum_reactions_thread_id_idx on public.forum_reactions (thread_id) where thread_id is not null;
create index forum_reactions_post_id_idx on public.forum_reactions (post_id) where post_id is not null;

alter table public.forum_reactions enable row level security;

create policy "Membros veem as reações"
  on public.forum_reactions for select
  to authenticated
  using (true);

create policy "Membros reagem em nome próprio"
  on public.forum_reactions for insert
  to authenticated
  with check (user_id = (select auth.uid()));

create policy "Membros removem as próprias reações"
  on public.forum_reactions for delete
  to authenticated
  using (user_id = (select auth.uid()));

revoke all on table public.forum_reactions from anon, authenticated;
grant select, delete on table public.forum_reactions to authenticated;
grant insert (user_id, thread_id, post_id, kind) on table public.forum_reactions to authenticated;
grant all on table public.forum_reactions to service_role;

create view public.forum_thread_reaction_counts
with (security_invoker = true)
as
  select r.thread_id, r.kind, count(*)::integer as total
  from public.forum_reactions r
  where r.thread_id is not null
  group by r.thread_id, r.kind;

create view public.forum_post_reaction_counts
with (security_invoker = true)
as
  select r.post_id, r.kind, count(*)::integer as total
  from public.forum_reactions r
  where r.post_id is not null
  group by r.post_id, r.kind;

revoke all on table public.forum_thread_reaction_counts from anon, authenticated;
revoke all on table public.forum_post_reaction_counts from anon, authenticated;
grant select on table public.forum_thread_reaction_counts to authenticated;
grant select on table public.forum_post_reaction_counts to authenticated;
grant all on table public.forum_thread_reaction_counts to service_role;
grant all on table public.forum_post_reaction_counts to service_role;
