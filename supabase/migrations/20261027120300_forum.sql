-- =============================================================================
-- Artemis · 04 — fórum: categorias, tópicos, respostas, anonimato, reações
-- =============================================================================
-- Anonimato (ver docs/03-banco-de-dados.md, seção "Anonimato"):
--   1. A cliente insere { author_id: <uid>, is_anonymous: true, ... }.
--   2. O trigger BEFORE INSERT (SECURITY DEFINER) confere que a categoria permite
--      anonimato e que author_id = auth.uid(); grava (id, uid) em
--      forum_anonymous_authorship e troca author_id por NULL.
--   3. O RLS (avaliado DEPOIS dos triggers BEFORE) só aceita linha anônima se a
--      autoria registrada para aquele id for exatamente a usuária atual
--      (private.is_anonymous_thread_author / is_anonymous_post_author).
--   4. Ninguém altera is_anonymous/author_id depois (sem GRANT + trigger).
--   5. Apagar a linha de autoria (ex.: conta excluída) apaga o conteúdo anônimo.

-- -----------------------------------------------------------------------------
-- forum_categories
-- -----------------------------------------------------------------------------
create table public.forum_categories (
  id smallint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(slug) <= 60),
  name text not null check (char_length(name) between 2 and 80),
  description text not null default '' check (char_length(description) <= 500),
  icon text not null default 'messages-square' check (icon ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  allow_anonymous boolean not null default false,
  sort_order smallint not null default 0,
  created_at timestamptz not null default now()
);
create index forum_categories_sort_order_idx on public.forum_categories (sort_order);

alter table public.forum_categories enable row level security;

create policy "Categorias do fórum são públicas"
  on public.forum_categories for select
  to anon, authenticated
  using (true);

revoke all on table public.forum_categories from anon, authenticated;
grant select on table public.forum_categories to anon, authenticated;
grant all on table public.forum_categories to service_role;

-- -----------------------------------------------------------------------------
-- forum_threads
