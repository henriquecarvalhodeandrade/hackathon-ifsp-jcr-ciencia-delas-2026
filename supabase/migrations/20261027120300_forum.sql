-- -----------------------------------------------------------------------------
-- forum_anonymous_authorship — quem escreveu cada conteúdo anônimo
-- FKs adiáveis: a linha é gravada pelo trigger BEFORE INSERT, antes de o tópico/
-- resposta existir de fato; a checagem acontece no fim da transação.
-- -----------------------------------------------------------------------------
create table public.forum_anonymous_authorship (
  id bigint generated always as identity primary key,
  thread_id uuid unique
    references public.forum_threads (id) on delete cascade deferrable initially deferred,
  post_id uuid unique
    references public.forum_posts (id) on delete cascade deferrable initially deferred,
  user_id uuid not null references public.profiles (id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint forum_anonymous_authorship_one_target check (num_nonnulls(thread_id, post_id) = 1)
);
comment on table public.forum_anonymous_authorship is
  'Autoria real de tópicos/respostas anônimos. Visível só para a autora e moderadoras. Escrita apenas por triggers.';
create index forum_anonymous_authorship_user_id_idx on public.forum_anonymous_authorship (user_id);

-- -----------------------------------------------------------------------------
-- Funções auxiliares (private)
-- VOLATILE de propósito: dentro do WITH CHECK do INSERT elas precisam enxergar a
-- linha de autoria gravada pelo trigger BEFORE do mesmo comando.
-- -----------------------------------------------------------------------------
-- "A usuária atual é a autora anônima deste tópico/resposta?" Devolve só um
-- booleano sobre a PRÓPRIA usuária — mesmo chamada diretamente, não revela a
-- autoria de ninguém.
create function private.is_anonymous_thread_author(p_thread_id uuid)
returns boolean
language sql
volatile
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.forum_anonymous_authorship a
    where a.thread_id = p_thread_id and a.user_id = (select auth.uid())
  );
$$;

create function private.is_anonymous_post_author(p_post_id uuid)
returns boolean
language sql
volatile
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.forum_anonymous_authorship a
    where a.post_id = p_post_id and a.user_id = (select auth.uid())
  );
$$;

-- Autora real (anônima ou não) — usada por notificações e RPCs internas.
create function private.thread_real_author(p_thread_id uuid)
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(
    t.author_id,
    (select a.user_id from public.forum_anonymous_authorship a where a.thread_id = t.id)
  )
  from public.forum_threads t
  where t.id = p_thread_id;
$$;

create function private.post_real_author(p_post_id uuid)
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(
    p.author_id,
    (select a.user_id from public.forum_anonymous_authorship a where a.post_id = p.id)
  )
  from public.forum_posts p
  where p.id = p_post_id;
$$;

revoke all on function private.is_anonymous_thread_author(uuid) from public, anon, authenticated;
revoke all on function private.is_anonymous_post_author(uuid) from public, anon, authenticated;
revoke all on function private.thread_real_author(uuid) from public, anon, authenticated;
revoke all on function private.post_real_author(uuid) from public, anon, authenticated;
grant execute on function private.is_anonymous_thread_author(uuid) to authenticated, service_role;
grant execute on function private.is_anonymous_post_author(uuid) to authenticated, service_role;
grant execute on function private.thread_real_author(uuid) to service_role;
grant execute on function private.post_real_author(uuid) to service_role;

-- -----------------------------------------------------------------------------
-- Triggers de forum_threads
-- -----------------------------------------------------------------------------
create function private.forum_threads_before_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
  v_allow_anonymous boolean;
  v_real_author uuid;
begin
  select c.allow_anonymous into v_allow_anonymous
  from public.forum_categories c where c.id = new.category_id;
  if not found then
    raise exception using errcode = 'CD015', message = 'Categoria do fórum não encontrada.';
  end if;

  new.title := btrim(new.title);
  new.tags := private.normalize_tags(new.tags);

  if v_uid is not null then
    if new.author_id is distinct from v_uid then
      raise exception using
        errcode = 'CD013',
        message = 'Autoria inválida: publique sempre com a sua própria conta.';
    end if;
    v_real_author := v_uid;
  elsif private.is_trusted_context() and new.author_id is not null then
    v_real_author := new.author_id; -- service_role/seed
  else
    raise exception using errcode = 'CD013', message = 'É preciso entrar na sua conta para publicar.';
  end if;

  if new.is_anonymous then
    if not v_allow_anonymous then
      raise exception using
        errcode = 'CD010',
        message = 'Esta categoria não permite publicações anônimas.';
    end if;
    -- ON CONFLICT: triggers BEFORE disparam antes da resolução de um
    -- "insert ... on conflict" (ex.: seed reaplicado). Clientes não escolhem o id
    -- e o RLS confere que a autoria registrada é da própria usuária.
    insert into public.forum_anonymous_authorship (thread_id, user_id)
    values (new.id, v_real_author)
    on conflict do nothing;
    new.author_id := null;
  end if;

  return new;
end;
$$;

create trigger forum_threads_before_insert
  before insert on public.forum_threads
  for each row execute function private.forum_threads_before_insert();

create function private.forum_threads_before_update()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.is_anonymous is distinct from old.is_anonymous or new.author_id is distinct from old.author_id then
    raise exception using
      errcode = 'CD013',
      message = 'Não é possível alterar a autoria ou o anonimato de uma publicação.';
  end if;

  if new.solution_post_id is distinct from old.solution_post_id and new.solution_post_id is not null
     and not exists (
       select 1 from public.forum_posts p
       where p.id = new.solution_post_id and p.thread_id = new.id
     ) then
    raise exception using
      errcode = 'CD014',
      message = 'A resposta escolhida como solução não pertence a este tópico.';
  end if;

  new.title := btrim(new.title);
  new.tags := private.normalize_tags(new.tags);
  if new.title is distinct from old.title or new.body is distinct from old.body then
    new.edited_at := now();
  end if;
  -- Novas respostas mudam só contadores/atividade: isso não conta como edição.
  if (to_jsonb(new) - 'reply_count' - 'last_activity_at' - 'updated_at')
     is distinct from (to_jsonb(old) - 'reply_count' - 'last_activity_at' - 'updated_at') then
    new.updated_at := now();
  end if;
  return new;
end;
$$;

create trigger forum_threads_before_update
  before update on public.forum_threads
  for each row execute function private.forum_threads_before_update();

-- -----------------------------------------------------------------------------
-- Triggers de forum_posts
-- -----------------------------------------------------------------------------
create function private.forum_posts_before_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
  v_locked boolean;
  v_allow_anonymous boolean;
  v_real_author uuid;
begin
  select t.is_locked, c.allow_anonymous into v_locked, v_allow_anonymous
  from public.forum_threads t
  join public.forum_categories c on c.id = t.category_id
  where t.id = new.thread_id;
  if not found then
    raise exception using errcode = 'CD015', message = 'Tópico não encontrado.';
  end if;

  if v_uid is not null then
    if new.author_id is distinct from v_uid then
      raise exception using
        errcode = 'CD013',
        message = 'Autoria inválida: responda sempre com a sua própria conta.';
    end if;
    v_real_author := v_uid;
  elsif private.is_trusted_context() and new.author_id is not null then
    v_real_author := new.author_id;
  else
    raise exception using errcode = 'CD013', message = 'É preciso entrar na sua conta para responder.';
  end if;

  if v_locked and v_uid is not null and not private.is_moderator() then
    raise exception using
      errcode = 'CD011',
      message = 'Este tópico está trancado e não aceita novas respostas.';
  end if;

  if new.is_anonymous then
    if not v_allow_anonymous then
      raise exception using
        errcode = 'CD010',
        message = 'Esta categoria não permite respostas anônimas.';
    end if;
    insert into public.forum_anonymous_authorship (post_id, user_id)
    values (new.id, v_real_author)
    on conflict do nothing;
    new.author_id := null;
  end if;

  return new;
end;
$$;

create trigger forum_posts_before_insert
  before insert on public.forum_posts
  for each row execute function private.forum_posts_before_insert();

create function private.forum_posts_before_update()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.is_anonymous is distinct from old.is_anonymous
     or new.author_id is distinct from old.author_id
     or new.thread_id is distinct from old.thread_id then
    raise exception using
      errcode = 'CD013',
      message = 'Não é possível alterar a autoria, o anonimato ou o tópico de uma resposta.';
  end if;
  if new.body is distinct from old.body then
    new.edited_at := now();
  end if;
  new.updated_at := now();
  return new;
end;
$$;

create trigger forum_posts_before_update
  before update on public.forum_posts
  for each row execute function private.forum_posts_before_update();

-- Mantém reply_count e last_activity_at do tópico.
create function private.forum_posts_after_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    update public.forum_threads t
    set reply_count = t.reply_count + 1,
        last_activity_at = greatest(t.last_activity_at, new.created_at)
    where t.id = new.thread_id;
    return null;
  end if;

  -- DELETE (inclusive em cascata ao apagar o tópico — aí o update não acha linha).
  update public.forum_threads t
  set reply_count = greatest(t.reply_count - 1, 0),
      last_activity_at = coalesce(
        (select max(p.created_at) from public.forum_posts p where p.thread_id = t.id),
        t.created_at
      )
  where t.id = old.thread_id;
  return null;
end;
$$;

create trigger forum_posts_after_insert
  after insert on public.forum_posts
  for each row execute function private.forum_posts_after_change();

create trigger forum_posts_after_delete
  after delete on public.forum_posts
  for each row execute function private.forum_posts_after_change();

-- LGPD: quando a linha de autoria some (ex.: conta excluída → cascata), o conteúdo
-- anônimo correspondente também é apagado.
create function private.forum_anonymous_authorship_after_delete()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if old.thread_id is not null then
    delete from public.forum_threads where id = old.thread_id;
  end if;
  if old.post_id is not null then
    delete from public.forum_posts where id = old.post_id;
  end if;
  return null;
end;
$$;

create trigger forum_anonymous_authorship_after_delete
  after delete on public.forum_anonymous_authorship
  for each row execute function private.forum_anonymous_authorship_after_delete();

revoke all on function private.forum_threads_before_insert() from public, anon, authenticated;
revoke all on function private.forum_threads_before_update() from public, anon, authenticated;
revoke all on function private.forum_posts_before_insert() from public, anon, authenticated;
revoke all on function private.forum_posts_before_update() from public, anon, authenticated;
revoke all on function private.forum_posts_after_change() from public, anon, authenticated;
revoke all on function private.forum_anonymous_authorship_after_delete() from public, anon, authenticated;

-- -----------------------------------------------------------------------------
-- RLS + GRANTs: forum_threads (fórum é só para membros)
-- -----------------------------------------------------------------------------
alter table public.forum_threads enable row level security;

create policy "Membros leem os tópicos"
  on public.forum_threads for select
  to authenticated
  using (true);

create policy "Membros criam tópicos com a própria autoria"
  on public.forum_threads for insert
  to authenticated
  with check (
    (not is_anonymous and author_id = (select auth.uid()))
    or (
      is_anonymous and author_id is null
      and private.is_anonymous_thread_author(id)
    )
  );

create policy "Autora ou moderação editam o tópico"
  on public.forum_threads for update
  to authenticated
  using (
    author_id = (select auth.uid())
    or (is_anonymous and private.is_anonymous_thread_author(id))
    or (select private.is_moderator())
  )
  with check (
    author_id = (select auth.uid())
    or (is_anonymous and private.is_anonymous_thread_author(id))
    or (select private.is_moderator())
  );

create policy "Autora ou moderação apagam o tópico"
  on public.forum_threads for delete
  to authenticated
  using (
    author_id = (select auth.uid())
    or (is_anonymous and private.is_anonymous_thread_author(id))
    or (select private.is_moderator())
  );

revoke all on table public.forum_threads from anon, authenticated;
grant select, delete on table public.forum_threads to authenticated;
grant insert (category_id, author_id, is_anonymous, title, body, tags)
  on table public.forum_threads to authenticated;
grant update (title, body, tags, solution_post_id) on table public.forum_threads to authenticated;
grant all on table public.forum_threads to service_role;

