-- -----------------------------------------------------------------------------
-- profile_embeddings — vetor 768d do perfil (Gemini). Só a dona lê/escreve; o
-- matching usa a RPC SECURITY DEFINER get_mentor_candidates().
-- -----------------------------------------------------------------------------
create table public.profile_embeddings (
  profile_id uuid primary key default auth.uid() references public.profiles (id) on delete cascade,
  embedding extensions.vector(768) not null,
  content_hash text not null check (char_length(content_hash) <= 128),
  model text not null check (char_length(model) <= 100),
  updated_at timestamptz not null default now()
);

create index profile_embeddings_embedding_hnsw_idx on public.profile_embeddings
  using hnsw (embedding extensions.vector_cosine_ops);

create trigger profile_embeddings_set_updated_at
  before update on public.profile_embeddings
  for each row execute function private.set_updated_at();

alter table public.profile_embeddings enable row level security;

create policy "Usuária lê o próprio embedding"
  on public.profile_embeddings for select
  to authenticated
  using (profile_id = (select auth.uid()));

-- Gravar exige consentimento de IA vigente: sem isso, um cálculo de embedding que
-- termina depois de a usuária revogar o consentimento recriaria o vetor que o
-- trigger profiles_after_consent_revoked acabou de apagar.
create policy "Usuária grava o próprio embedding"
  on public.profile_embeddings for insert
  to authenticated
  with check (
    profile_id = (select auth.uid())
    and exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.ai_consent)
  );

create policy "Usuária atualiza o próprio embedding"
  on public.profile_embeddings for update
  to authenticated
  using (profile_id = (select auth.uid()))
  with check (
    profile_id = (select auth.uid())
    and exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.ai_consent)
  );

create policy "Usuária apaga o próprio embedding"
  on public.profile_embeddings for delete
  to authenticated
  using (profile_id = (select auth.uid()));

revoke all on table public.profile_embeddings from anon, authenticated;
grant select, delete on table public.profile_embeddings to authenticated;
-- profile_id entra no UPDATE porque o upsert do PostgREST inclui todas as colunas
-- enviadas no "DO UPDATE SET" (o RLS garante que continua sendo a própria linha).
grant insert (profile_id, embedding, content_hash, model) on table public.profile_embeddings to authenticated;
grant update (profile_id, embedding, content_hash, model) on table public.profile_embeddings to authenticated;
grant all on table public.profile_embeddings to service_role;

-- Revogar o consentimento de IA apaga o embedding (LGPD: mínimo necessário).
create function private.profiles_after_consent_revoked()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  delete from public.profile_embeddings where profile_id = new.id;
  return null;
end;
$$;
revoke all on function private.profiles_after_consent_revoked() from public, anon, authenticated;

create trigger profiles_after_consent_revoked
  after update of ai_consent on public.profiles
  for each row
  when (old.ai_consent and not new.ai_consent)
  execute function private.profiles_after_consent_revoked();
