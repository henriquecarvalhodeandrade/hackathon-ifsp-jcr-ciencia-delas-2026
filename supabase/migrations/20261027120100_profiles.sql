-- -----------------------------------------------------------------------------
-- research_areas — catálogo (grandes áreas do CNPq + subáreas)
-- -----------------------------------------------------------------------------
create table public.research_areas (
  id smallint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(slug) <= 80),
  name text not null check (char_length(name) between 2 and 120),
  big_area text not null check (char_length(big_area) between 2 and 120),
  created_at timestamptz not null default now()
);
comment on table public.research_areas is
  'Áreas do conhecimento (grandes áreas do CNPq + subáreas). Linhas em que name = big_area representam a própria grande área.';

create index research_areas_big_area_idx on public.research_areas (big_area);

alter table public.research_areas enable row level security;

create policy "Áreas de pesquisa são públicas"
  on public.research_areas for select
  to anon, authenticated
  using (true);

revoke all on table public.research_areas from anon, authenticated;
grant select on table public.research_areas to anon, authenticated;
grant all on table public.research_areas to service_role;

-- -----------------------------------------------------------------------------
-- profiles — 1:1 com auth.users
-- -----------------------------------------------------------------------------
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text not null default '' check (char_length(full_name) <= 120),
  avatar_url text check (char_length(avatar_url) <= 500 and avatar_url ~* '^https?://'),
  pronouns text check (char_length(pronouns) <= 30),
  headline text check (char_length(headline) <= 160),
  bio text check (char_length(bio) <= 2000),
  institution text check (char_length(institution) <= 160),
  city text check (char_length(city) <= 80),
  state char(2) check (state ~ '^[A-Z]{2}$'),
  career_stage public.career_stage,
  keywords text[] not null default '{}'
    check (private.text_array_ok(keywords, 15, 60) and keywords = private.normalize_tags(keywords)),
  mentorship_topics text[] not null default '{}'
    check (
      private.text_array_ok(mentorship_topics, 15, 40)
      and mentorship_topics <@ array[
        'carreira-academica', 'bolsas-editais', 'escrita-cientifica', 'pos-graduacao',
        'internacionalizacao', 'maternidade-ciencia', 'lideranca', 'industria-inovacao',
        'empreendedorismo', 'saude-mental', 'divulgacao-cientifica', 'programacao-dados',
        'metodologia', 'oratoria', 'networking'
      ]::text[]
    ),
  lattes_url text check (char_length(lattes_url) <= 300 and lattes_url ~* '^https?://\S+$'),
  orcid text check (orcid ~* '^(https?://)?(orcid\.org/)?\d{4}-\d{4}-\d{4}-\d{3}[0-9X]$'),
  linkedin_url text check (char_length(linkedin_url) <= 300 and linkedin_url ~* '^https?://\S+$'),
  website_url text check (char_length(website_url) <= 300 and website_url ~* '^https?://\S+$'),
  is_mentor boolean not null default false,
  seeks_mentorship boolean not null default false,
  mentor_capacity smallint not null default 2 check (mentor_capacity between 0 and 20),
  mentor_available boolean not null default true,
  meeting_formats public.meeting_format[] not null default '{online}'
    check (cardinality(meeting_formats) <= 3),
  languages text[] not null default '{pt}' check (private.text_array_ok(languages, 10, 20)),
  mentoring_goals text check (char_length(mentoring_goals) <= 1000),
  mentoring_offer text check (char_length(mentoring_offer) <= 1000),
  role public.user_role not null default 'member',
  ai_consent boolean not null default false,
  ai_consent_at timestamptz,
  onboarded_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
comment on table public.profiles is
  'Perfil público (para membros) de cada usuária. Criado automaticamente no cadastro.';
comment on column public.profiles.role is
  'Papel na plataforma. Não pode ser alterado pela própria usuária (sem GRANT de UPDATE).';
comment on column public.profiles.ai_consent is
  'Consentimento para uso de IA (18+ e aviso de uso de dados). Revogar apaga o embedding.';

create index profiles_mentor_idx on public.profiles (is_mentor, mentor_available)
  where is_mentor and onboarded_at is not null;
create index profiles_role_idx on public.profiles (role) where role <> 'member';
create index profiles_onboarded_at_idx on public.profiles (onboarded_at);
create index profiles_full_name_trgm_idx on public.profiles
  using gin (full_name extensions.gin_trgm_ops);
create index profiles_keywords_idx on public.profiles using gin (keywords);

-- Normalização antes de gravar: strings vazias viram NULL, UF maiúscula, tags em
-- minúsculas, data do consentimento de IA.
create function private.profiles_before_write()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.full_name := left(btrim(coalesce(new.full_name, '')), 120);
  new.avatar_url := nullif(btrim(new.avatar_url), '');
  new.pronouns := nullif(btrim(new.pronouns), '');
  new.headline := nullif(btrim(new.headline), '');
  new.bio := nullif(btrim(new.bio), '');
  new.institution := nullif(btrim(new.institution), '');
  new.city := nullif(btrim(new.city), '');
  new.state := nullif(upper(btrim(new.state)), '');
  new.lattes_url := nullif(btrim(new.lattes_url), '');
  new.orcid := nullif(btrim(new.orcid), '');
  new.linkedin_url := nullif(btrim(new.linkedin_url), '');
  new.website_url := nullif(btrim(new.website_url), '');
  new.mentoring_goals := nullif(btrim(new.mentoring_goals), '');
  new.mentoring_offer := nullif(btrim(new.mentoring_offer), '');
  new.keywords := private.normalize_tags(new.keywords);
  new.mentorship_topics := private.normalize_tags(new.mentorship_topics);
  new.languages := private.normalize_tags(new.languages);
  new.meeting_formats := coalesce(new.meeting_formats, '{online}');

  -- O momento do consentimento de IA é registro (LGPD / termos do Gemini): quem
  -- define é o banco, não a cliente. Concedido agora → now(); mantido → valor
  -- antigo; revogado → NULL. Só contexto confiável (seed/service role) informa
  -- uma data própria.
  if not new.ai_consent then
    new.ai_consent_at := null;
  elsif not private.is_trusted_context() then
    new.ai_consent_at := case
      when tg_op = 'UPDATE' and old.ai_consent then coalesce(old.ai_consent_at, now())
      else now()
    end;
  elsif new.ai_consent_at is null then
    new.ai_consent_at := now();
  end if;

  if tg_op = 'UPDATE' then
    new.updated_at := now();
  end if;
  return new;
end;
$$;

create trigger profiles_before_write
  before insert or update on public.profiles
  for each row execute function private.profiles_before_write();

-- Cria o perfil automaticamente no cadastro (e-mail/senha, magic link ou OAuth).
create function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_meta jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  v_name text;
  v_avatar text;
begin
  v_name := left(btrim(coalesce(
    nullif(btrim(v_meta ->> 'full_name'), ''),
    nullif(btrim(v_meta ->> 'name'), ''),
    ''
  )), 120);

  v_avatar := coalesce(nullif(btrim(v_meta ->> 'avatar_url'), ''), nullif(btrim(v_meta ->> 'picture'), ''));
  -- Só aceita URLs http(s) razoáveis; qualquer outra coisa é descartada para não
  -- impedir o cadastro por causa de um CHECK.
  if v_avatar is not null and (v_avatar !~* '^https?://\S+$' or char_length(v_avatar) > 500) then
    v_avatar := null;
  end if;

  insert into public.profiles (id, full_name, avatar_url)
  values (new.id, v_name, v_avatar)
  on conflict (id) do nothing;

  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function private.handle_new_user();

-- Funções de papel usadas em políticas (SECURITY DEFINER para não depender do RLS
-- de profiles e evitar recursão).
create function private.is_moderator()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid()) and p.role in ('moderator', 'admin')
  );
$$;

create function private.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid()) and p.role = 'admin'
  );
$$;

revoke all on function private.profiles_before_write() from public, anon, authenticated;
revoke all on function private.handle_new_user() from public, anon, authenticated;
revoke all on function private.is_moderator() from public, anon, authenticated;
revoke all on function private.is_admin() from public, anon, authenticated;
grant execute on function private.is_moderator() to anon, authenticated, service_role;
grant execute on function private.is_admin() to anon, authenticated, service_role;

